import { useMemo } from 'react'
import { GlassCard } from '../../components/glass'
import { renderMarkdown } from '../../lib/markdown'
import { ADMIN_GUIDE_MD } from './adminGuideText'
import { useAuth } from '../../contexts/AuthContext'
import { NAV_ITEMS } from './index'

// Рендерер общий с юридическими страницами — см. src/lib/markdown.tsx.
//
// ВАЖНО: всё в этом файле меняет только то, что видит рядовой админ.
// ADMIN_GUIDE_MD (владельческий, полный текст) не редактируется — владелец
// как читал полный гайд, так и продолжает его читать без изменений.

// Подразделы под "## Разделы админки" называются точно так же, как пункты
// меню (см. ADMIN_GUIDE.md) — оставляем только те, что доступны тарифу «админ».
const ALLOWED_SECTION_LABELS = new Set(NAV_ITEMS.filter(i => !i.ownerOnly).map(i => i.label))

// Верхнеуровневые "## "-блоки, которые вообще имеет смысл показывать админу.
// «VIP-система», «Финансовая логика», «Частые вопросы» и «Важные правила» —
// не заголовочные списки/списки-пункты вперемешку про owner-only разделы
// (Финансы, Пополнения, Выводы, Прогрев расписания, ГОСТ и т.д.), почистить
// их построчно надёжно нельзя — проще не показывать целиком, чем частично
// деанонить владельческую механику через щели фильтра.
const ALLOWED_H2 = new Set(['Доступ в админку', 'Разделы админки', 'Юридические документы'])

// Точечные вырезки текста, актуального только владельцу (рассказывает про
// вещи, которых у рядового админа просто нет в интерфейсе — тумблер
// «Смотреть как админ», бейдж «ВЛАДЕЛЕЦ», кнопки выдачи прав и т.д.),
// плюс все упоминания Telegram — пока не решено, будет ли у админов доступ
// к боту. Каждая пара — [что вырезать, на что заменить] (обычно на пусто).
const ADMIN_TEXT_CUTS: [RegExp | string, string][] = [
  // "Два уровня доступа..." + тумблер «Смотреть как админ» — про сам факт
  // существования тиров и владельческую фичу, админу читать незачем.
  [
    /\*\*Два уровня доступа: владелец и админ\.\*\*[\s\S]*?не меняются\.\n\n/,
    '',
  ],
  // "Всего 16 рабочих разделов..." — админу видно не 16, а меньше.
  [
    'Всего 16 рабочих разделов плюс эта Справка. Ниже — по каждому.',
    'Ниже — по каждому доступному вам разделу.',
  ],
  // Модерация: что реально происходит с флагом + исключение про сажированный
  // обмен контактами — сама regex-проверка сейчас отключена в коде.
  [
    /Важно понимать, что происходит с такими сообщениями:[\s\S]*?не считается нарушением\.\n\n/,
    '',
  ],
  [
    '**Уведомления в Telegram.** Regex-флаг (контакты в сообщении) уходит в Telegram сразу,\nв момент отправки сообщения. По ИИ-флагам приходит одно сводное уведомление на заказ\n(«подозрительных сообщений: N»), а не по сообщению на каждое, — иначе после завершения\nкрупной сделки прилетала бы пачка. Поэтому раздел больше не нужно проверять вручную.',
    '',
  ],
  // Споры и Форум — ещё два прямых упоминания Telegram.
  [
    '\n\nВ оба случая уходит уведомление в Telegram.',
    '',
  ],
  [
    '«AI-флаги», и в Telegram уходит уведомление.',
    '«AI-флаги».',
  ],
  [
    'О каждом новом обращении приходит уведомление в Telegram — с ником, темой и началом\nтекста, так что раздел не нужно проверять вручную.',
    'О каждом новом обращении вы узнаёте, зайдя в раздел — список обновляется сам.',
  ],
  [
    '  О снятии 2FA и о неудачных попытках приходит уведомление в Telegram.\n',
    '',
  ],
  // Пользователи: бейдж «ВЛАДЕЛЕЦ» и кнопки выдачи ролей — у админа их нет.
  [
    /Владелец дополнительно видит метку \*\*ВЛАДЕЛЕЦ\*\*[\s\S]*?через API тоже нельзя\.\n\n/,
    '',
  ],
  [
    /- \*\*Сделать администратором \/ Снять админа\*\*, а для владельцев[\s\S]*?вернёт ошибку\.\n/,
    '',
  ],
  ['Три действия:', 'Два действия:'],
  // Юридические документы: кто их правит и про плейсхолдер ИП — не имеет
  // отношения к работе админа день в день.
  [
    /\*\*Управления этими документами в админке нет\.\*\*[\s\S]*?к реальному запуску независимо от того, что её техническая часть работает\.\n\n/,
    '',
  ],
]

/**
 * Урезает гайд для тарифа «админ»: оставляет только разрешённые "## "-блоки
 * (см. ALLOWED_H2), внутри "## Разделы админки" — только "###"-подразделы
 * из разрешённого набора («Настройки» и «Справка» тоже выкидываются целиком —
 * первая описывает в основном owner-only секции, вторая просто самоописание
 * страницы), плюс серия точечных вырезок (см. ADMIN_TEXT_CUTS) для мест
 * внутри оставленных разделов, актуальных только владельцу.
 */
function filterForAdminTier(mdRaw: string): string {
  // adminGuideText.ts хранит текст с CRLF — паттерны ниже завязаны на '\n\n',
  // поэтому нормализуем один раз в начале (безопасно: рендерер markdown
  // одинаково понимает оба варианта).
  const md = mdRaw.replace(/\r\n/g, '\n')
  const blocks = md.split(/\n(?=## )/)

  const kept = blocks.slice(1).filter(block => {
    const title = block.match(/^## (.+)$/m)?.[1]?.trim()
    return title != null && ALLOWED_H2.has(title)
  }).map(block => {
    if (!block.startsWith('## Разделы админки')) return block

    const parts = block.split(/\n(?=### )/)
    const header = parts[0]
    const keptSubsections = parts.slice(1).filter(part => {
      const title = part.match(/^### (.+)$/m)?.[1]?.trim()
      return title === 'Настройки' || title === 'Справка'
        ? false
        : title != null && ALLOWED_SECTION_LABELS.has(title)
    })
    return header + keptSubsections.join('')
  })

  // Без вступительной "Документ описывает..." преамбулы — это владельческая
  // мета-информация о самом гайде (что покрыто, где искать план работ и т.д.),
  // рядовому админу нерелевантна.
  let result = '# Гайд администратора Ebu.Gubkin\n\n' + kept.join('')

  for (const [pattern, replacement] of ADMIN_TEXT_CUTS) {
    result = typeof pattern === 'string'
      ? result.split(pattern).join(replacement)
      : result.replace(pattern, replacement)
  }

  return result
}

export default function AdminHelp() {
  const { profile } = useAuth()
  const md = profile?.is_owner ? ADMIN_GUIDE_MD : filterForAdminTier(ADMIN_GUIDE_MD)
  const content = useMemo(() => renderMarkdown(md), [md])
  return (
    <GlassCard className="rounded-2xl p-5 sm:p-8 max-w-4xl">
      {content}
    </GlassCard>
  )
}
