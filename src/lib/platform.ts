/**
 * Отправлять ли сообщение по Enter в многострочных полях ввода (чаты).
 *
 * На тач-устройствах — нет: экранная клавиатура не даёт нажать Shift+Enter,
 * поэтому Enter, отправляющий сообщение, полностью лишает возможности
 * поставить перенос строки. Там Enter переносит строку, а отправка — кнопкой.
 *
 * `pointer: coarse` = основное указательное устройство неточное, т.е. палец.
 * Ноутбук с тачскрином и мышью останется `fine` — у него настоящая клавиатура
 * и привычная отправка по Enter сохраняется.
 *
 * Тип указателя за сессию не меняется, поэтому считаем один раз при импорте.
 */
export const ENTER_SENDS_MESSAGE = !window.matchMedia('(pointer: coarse)').matches
